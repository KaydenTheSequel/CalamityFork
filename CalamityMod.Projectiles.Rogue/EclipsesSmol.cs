		base.Projectile.ignoreWater = true;
		base.Projectile.DamageType = RogueDamageClass.Instance;
		base.Projectile.MaxUpdates = 2;
		base.Projectile.timeLeft = 75 * base.Projectile.MaxUpdates;
	}

