		Lighting.AddLight(base.Projectile.Center, (float)(255 - base.Projectile.alpha) * 1f / 255f, 0f, 0f);
		base.Projectile.frameCounter++;
		if (base.Projectile.frameCounter > 4)
		{
			base.Projectile.frame++;
			base.Projectile.frameCounter = 0;
		}
		if (base.Projectile.frame >= 4)
		{
			base.Projectile.frame = 0;
		}
		if (base.Projectile.alpha > 0)
		{
			base.Projectile.alpha -= 10;
		}
		if (base.Projectile.alpha <= 25)
		{
			NPC potentialTarget = base.Projectile.Center.MinionHoming(700f, Main.player[base.Projectile.owner]);
			if (potentialTarget != null)
			{
				base.Projectile.velocity = (base.Projectile.velocity * 20f + base.Projectile.SafeDirectionTo(potentialTarget.Center) * 16f) / 21f;
			}
		}
	}

